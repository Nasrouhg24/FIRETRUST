import { test, expect, type Page } from '@playwright/test'

const nav = (page: Page, name: string) => page.getByRole('navigation').getByRole('button', { name })

test('journey: discover, compare, calendar, evidence and exports on the real archive', async ({ page }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  // Discover: the message and the illusion with real data
  await expect(page.getByRole('heading', { level: 1, name: 'Not every change in satellite detections is a change in fire.' })).toBeVisible()
  await expect(page.getByRole('img', { name: /Annual active cell-days by satellite/ })).toBeVisible({ timeout: 30000 })
  await expect(page.getByText(/VIIRS S-NPP recorded \d+(\.\d)?× as many/)).toBeVisible()
  await page.getByRole('button', { name: 'Switch sensors mid-record' }).click()
  await expect(page.getByText(/inherits a step of about/)).toBeVisible()
  await page.getByRole('button', { name: 'Estimated common scale' }).click()
  await expect(page.getByText(/what the model estimates S-NPP/)).toBeVisible()
  await expect(page.getByText('not the true amount of fire').first()).toBeVisible()
  await expect(page.locator('.error')).toHaveCount(0)
  await page.screenshot({ path: '../artifacts/discover-desktop.png', fullPage: true })

  // Calendar: recorded, zero and missing stay distinct; exports work
  await nav(page, 'Calendar').click()
  await expect(page.locator('.heatmap')).toBeVisible({ timeout: 30000 })
  await expect(page.getByRole('gridcell', { name: /2002-01: no matching records/ })).toBeVisible()
  await expect(page.getByRole('gridcell', { name: /2024-08: \d+ active cell days/ })).toBeVisible()
  await expect(page.getByRole('gridcell', { name: /2002-12: 0 active cell days recorded, complete archive file/ })).toBeVisible()
  const pngDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export PNG' }).click()
  expect((await pngDownload).suggestedFilename()).toBe('firetrust-calendar.png')
  await page.getByRole('gridcell', { name: /2024-08:/ }).click()
  await expect(page.locator('.month-detail')).toContainText('Aug 2024')
  await expect(page.locator('.month-detail')).toContainText('VIIRS S-NPP recorded')
  await page.screenshot({ path: '../artifacts/calendar-desktop.png', fullPage: true })
  await page.getByRole('combobox', { name: 'Calendar view' }).selectOption('estimate')
  await expect(page.getByRole('gridcell', { name: /2024-08: estimate [\d,.]+; (residual band|no band)/ })).toBeVisible()
  await expect(page.getByRole('gridcell', { name: /2005-08: estimate .*extrapolated/ })).toBeVisible()
  const estimatedCsv = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Download estimates with provenance' }).click()
  expect((await estimatedCsv).suggestedFilename()).toBe('firetrust-harmonized.csv')
  await page.screenshot({ path: '../artifacts/calendar-harmonized.png', fullPage: true })
  await page.getByRole('combobox', { name: 'Calendar view' }).selectOption('anomaly')
  await expect(page.getByRole('gridcell', { name: /2020-01: delta/ })).toBeVisible({ timeout: 30000 })
  await page.getByRole('combobox', { name: 'Calendar view' }).selectOption('availability')
  await expect(page.getByRole('gridcell', { name: /2024-08: detections recorded; cloud and overpass coverage unknown/ })).toHaveText('●')

  // Compare: three clearly separated series, keyboard month comparison, progressive detail
  await nav(page, 'Compare').click()
  await expect(page.getByRole('img', { name: /Monthly active cell-days: MODIS Aqua as recorded, VIIRS S-NPP as recorded, and the model estimate/ })).toBeVisible({ timeout: 30000 })
  await page.getByRole('slider', { name: 'Comparison month' }).focus()
  await page.getByRole('slider', { name: 'Comparison month' }).press('End')
  await expect(page.locator('.readout')).toContainText('Dec 2025')
  const estimateToggle = page.getByRole('group', { name: 'Series shown' }).getByRole('button', { name: 'Estimate on the S-NPP scale' })
  await estimateToggle.click()
  await expect(estimateToggle).toHaveAttribute('aria-pressed', 'false')
  await estimateToggle.click()
  await page.getByRole('group', { name: 'MODIS satellite' }).getByRole('button', { name: 'Terra' }).click()
  await expect(page.getByRole('img', { name: /Monthly active cell-days: MODIS Terra as recorded/ })).toBeVisible({ timeout: 30000 })
  await page.getByText('How it was computed').click()
  await expect(page.getByText(/Registered model/)).toBeVisible()
  await expect(page.getByText(/Aqua does better is not established/)).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: '../artifacts/sensor-lab-desktop.png', fullPage: true })

  // Evidence: validation, limits, provenance
  await nav(page, 'Evidence').click()
  await expect(page.getByRole('heading', { name: 'Source ledger' })).toBeVisible()
  await expect(page.getByText('Every bias is negative')).toBeVisible({ timeout: 30000 })
  await page.getByRole('button', { name: 'Inspect' }).first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog').getByText('SHA-256')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const csvDownload = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Export filtered detections as CSV' }).click()
  expect((await csvDownload).suggestedFilename()).toBe('firetrust-raw.csv')
  expect(errors).toEqual([])
})

