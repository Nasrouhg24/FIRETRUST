test('explore: map, custom coordinates, empty selection and mobile layout', async ({ page }) => {
  test.setTimeout(120000)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await nav(page, 'Explore').click()
  await expect(page.getByRole('status')).toHaveCount(0, { timeout: 30000 })
  await expect(page.getByRole('link', { name: 'Natural Earth', exact: true })).toBeVisible()
  await expect(page.locator('.statline dt').first()).not.toHaveText('0')
  await page.getByRole('button', { name: 'Dates and custom area' }).click()
  await page.getByRole('textbox', { name: 'Custom bounding box' }).fill('-1,0,0,1')
  await page.getByRole('button', { name: 'Apply area' }).click()
  await expect(page.getByRole('heading', { name: 'No observations in this selection.' })).toBeVisible({ timeout: 30000 })
  await page.getByRole('combobox', { name: 'Region' }).selectOption('portugal_mainland')
  await expect(page.getByRole('heading', { name: 'No observations in this selection.' })).toHaveCount(0)
  await expect(page.locator('.statline dt').first()).not.toHaveText('0')
  await page.screenshot({ path: '../artifacts/overview-mobile.png', fullPage: true })
  for (const tab of ['Discover', 'Compare', 'Calendar', 'Evidence']) {
    await nav(page, tab).click()
    await page.waitForLoadState('networkidle')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `${tab} has no horizontal overflow`).toBe(true)
  }
})
